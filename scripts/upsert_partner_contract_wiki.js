const { PrismaClient } = require('@prisma/client')

const prisma = new PrismaClient()

function plainText (markdown = '') {
  return String(markdown)
    .replace(/!\[[^\]]*\]\([^)]+\)/g, ' ')
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/[#>*_`[\]-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

function slugify (value = '') {
  return String(value)
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9а-яё]+/gi, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 120)
}

async function upsertPage ({ tenantId, title, contentMarkdown, parentId, sortOrder, sourcePageId }) {
  const existing = await prisma.wikiPage.findFirst({ where: { tenantId, title } })
  const data = {
    title,
    slug: slugify(title),
    contentMarkdown,
    contentText: plainText(contentMarkdown),
    parentId,
    sortOrder,
    isPublished: true
  }

  if (existing) return prisma.wikiPage.update({ where: { id: existing.id }, data })

  return prisma.wikiPage.create({
    data: {
      tenantId,
      ...data,
      sourceProvider: 'riderra',
      sourcePageId
    }
  })
}

