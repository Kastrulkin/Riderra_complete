function validateArticles () {
  const allArticles = [...contractArticles, ...reviewArticles]
  const titles = new Set()

  for (const article of allArticles) {
    if (!article.title || !article.content && !article.preserveExisting) {
      throw new Error(`Invalid article definition: ${article.title || '(untitled)'}`)
    }
    if (titles.has(article.title)) throw new Error(`Duplicate wiki article title: ${article.title}`)
    titles.add(article.title)
    if (article.section && !['active', 'former', 'potential'].includes(article.section)) {
      throw new Error(`Unknown article section for ${article.title}: ${article.section}`)
    }
    if (article.content && /Источник:\*\* undefined|Источник:\s*undefined/.test(article.content)) {
      throw new Error(`Undefined source in article: ${article.title}`)
    }
  }

  return allArticles.length
}

