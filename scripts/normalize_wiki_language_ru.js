function replaceWikiLinks (content) {
  let result = String(content || '')
  for (const [oldTitle, newTitle] of Object.entries(titleMap)) {
    result = result
      .split(`[[${oldTitle}]]`).join(`[[${newTitle}]]`)
      .split(`[[${oldTitle}|`).join(`[[${newTitle}|`)
  }
  return result
    .replace('# Группа координации (aka Света)', '# Группа координации (Света)')
    .replace('# Диспетчеры aka Макс и Алёна', '# Диспетчеры (Макс и Алёна)')
    .replace('# Работа с email', '# Работа с электронной почтой')
    .replace('ярлыком Complaints to do', 'ярлыком Complaints to do («Жалобы к обработке»)')
    .replace('7. Done.', '7. Нажимаем Done («Готово»).')
    .replace('Статус: draft / active / paused / archived', 'Статус: черновик / действует / приостановлен / архив')
}

async function main () {
  const pages = await prisma.wikiPage.findMany({ where: { isPublished: true } })
  const byTitle = new Map(pages.map(page => [page.title, page]))
  const renamed = []

  for (const [oldTitle, newTitle] of Object.entries(titleMap)) {
    const page = byTitle.get(oldTitle) || byTitle.get(newTitle)
    if (!page) throw new Error(`Wiki page not found: ${oldTitle}`)
    const contentMarkdown = rewrittenPages[newTitle] || replaceWikiLinks(page.contentMarkdown)
    await prisma.wikiPage.update({
      where: { id: page.id },
      data: {
        title: newTitle,
        slug: slugify(newTitle),
        contentMarkdown,
        contentText: plainText(contentMarkdown)
      }
    })
    renamed.push(`${oldTitle} -> ${newTitle}`)
  }

  const refreshed = await prisma.wikiPage.findMany({ where: { isPublished: true } })
  let linkedPages = 0
  for (const page of refreshed) {
    const contentMarkdown = replaceWikiLinks(page.contentMarkdown)
    if (contentMarkdown === page.contentMarkdown) continue
    await prisma.wikiPage.update({
      where: { id: page.id },
      data: { contentMarkdown, contentText: plainText(contentMarkdown) }
    })
    linkedPages += 1
  }

  console.log(JSON.stringify({ renamed, rewritten: Object.keys(rewrittenPages), linkedPages }, null, 2))
}

main()
  .catch(error => {
    console.error(error)
    process.exitCode = 1
  })
  .finally(async () => {
    await prisma.$disconnect()
  })
