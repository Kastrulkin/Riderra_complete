function plainText (markdown = '') {
  return String(markdown)
    .replace(/!\[[^\]]*\]\([^)]+\)/g, ' ')
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/[#>*_`[\]-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

function slugify (value = '') {
  return String(value)
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9а-яё]+/gi, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 120)
}

const previousTitles = {
  'Mozio: API водителя и автомобиля': 'Mozio Driver and Vehicle API',
  'Mozio: API отслеживания поездки': 'Mozio Tracking API'
}

async function updatePage (tenantId, title, contentMarkdown) {
  const oldTitle = previousTitles[title]
  const page = await prisma.wikiPage.findFirst({
    where: {
      tenantId,
      title: oldTitle ? { in: [title, oldTitle] } : title
    }
  })
  if (!page) throw new Error(`Wiki page not found: ${title}`)
  return prisma.wikiPage.update({
    where: { id: page.id },
    data: {
      title,
      slug: slugify(title),
      contentMarkdown,
      contentText: plainText(contentMarkdown),
      isPublished: true
    }
  })
}

